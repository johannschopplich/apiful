import * as fsp from 'node:fs/promises'
import * as path from 'node:path'
import { consola } from 'consola'

interface HttpStatus {
  code: number
  phrase: string
  constant: string
  referenceUrl: string
  isObsolete: boolean
}

const REGISTRY_URL = 'https://www.iana.org/assignments/http-status-codes/http-status-codes-1.csv'
const rootDir = path.join(import.meta.dirname, '..')

const httpStatuses = parseRegistry(await fetchRegistry())

await writeModule('src/generated/http-status-codes.ts', httpStatuses, status => String(status.code))
await writeModule('src/generated/http-status-phrases.ts', httpStatuses, status => `'${status.phrase.replaceAll('\'', '\\\'')}'`)
consola.success(`Generated ${httpStatuses.length} HTTP status codes and phrases from the IANA registry`)

async function fetchRegistry() {
  const response = await fetch(REGISTRY_URL)
  if (!response.ok) {
    throw new Error(`Failed to retrieve the IANA HTTP Status Code Registry: ${response.status} ${response.statusText}`)
  }
  return await response.text()
}

function parseRegistry(csv: string) {
  const statuses: HttpStatus[] = []

  for (const line of csv.trim().split(/\r?\n/).slice(1)) {
    const [value = '', description = '', reference = ''] = parseCsvLine(line)

    // Skips ranges and the unassigned and unused codes, which name no status, and temporary registrations, which expire.
    if (!/^\d{3}$/.test(value) || description === 'Unassigned' || description === '(Unused)' || description.includes('(TEMPORARY'))
      continue

    const isObsolete = description.endsWith('(OBSOLETED)')
    const phrase = description.replace(/\s*\(OBSOLETED\)$/, '')

    statuses.push({
      code: Number(value),
      phrase,
      constant: phrase.toUpperCase().replaceAll(/[^A-Z0-9]+/g, '_'),
      referenceUrl: resolveReferenceUrl(value, reference),
      isObsolete,
    })
  }

  return statuses
}

function parseCsvLine(line: string) {
  const fields: string[] = []
  // Matches one field – quoted with doubled inner quotes, or bare – followed by its separator.
  for (const match of line.matchAll(/("(?:[^"]|"")*"|[^,]*)(,|$)/g)) {
    const field = match[1]!
    fields.push(field.startsWith('"') ? field.slice(1, -1).replaceAll('""', '"') : field)
    if (match[2] === '')
      break
  }
  return fields
}

function resolveReferenceUrl(value: string, reference: string) {
  const match = reference.match(/\[RFC ?(\d+)(?:, Section ([\d.]+))?\]/)
  if (!match)
    throw new Error(`HTTP status ${value} has no RFC reference: ${reference}`)

  const [, rfcNumber, section] = match
  return `https://www.rfc-editor.org/rfc/rfc${rfcNumber}.html${section ? `#section-${section}` : ''}`
}

async function writeModule(fileName: string, statuses: HttpStatus[], toInitializer: (status: HttpStatus) => string) {
  const declarations = statuses.map(status => [
    '/**',
    ` * ${status.code} ${status.phrase}`,
    ' *',
    ...(status.isObsolete ? [' * @deprecated Marked obsolete in the IANA registry.'] : []),
    ` * @see ${status.referenceUrl}`,
    ' */',
    `export const ${status.constant} = ${toInitializer(status)}`,
  ].join('\n'))

  const content = [
    '// Generated by `pnpm run generate:http-status-codes` – do not edit.',
    `// Source: IANA HTTP Status Code Registry, ${REGISTRY_URL}`,
    ...declarations,
  ].join('\n')

  await fsp.writeFile(path.join(rootDir, fileName), `${content}\n`)
}
